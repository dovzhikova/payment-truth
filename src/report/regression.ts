// A node:test file the shop owner can keep in their repo: it reruns every
// scenario against their handler and fails on any non-PASS verdict.

export function regressionTestSource(handlerPath: string): string {
  return `// Generated by Payment Truth. Run with: node --test payment-truth.regression.test.ts
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { runMatrix } from './src/matrix.ts';

const mod = await import(${JSON.stringify(handlerPath)});
const factory = Object.entries(mod).find(([k, v]) => k.startsWith('create') && typeof v === 'function')?.[1];

for (const seed of [1, 2, 3]) {
  test(\`agent traffic, seed \${seed}: every scenario passes I1-I4\`, async () => {
    assert.ok(factory, 'handler module exports a create* factory');
    for (const { run, verdicts } of await runMatrix(factory, seed)) {
      const bad = verdicts.filter((v) => v.result !== 'PASS');
      assert.deepEqual(bad, [], \`\${run.scenario} \${JSON.stringify(run.params)}\`);
    }
  });
}
`;
}
